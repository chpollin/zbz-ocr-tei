/* Entity overview page: per-document entity counts and certainty classes.
   Data: data/entity_overview.json (generated by scripts/edition/generate_entity_overview.py),
   data/entities.json (gid -> label/category), data/catalog.json (titles, workflow status).
   Read-only; all text reaches the DOM via textContent. */

window.ZBZ = window.ZBZ || {};

ZBZ.EntityOverview = (() => {
  'use strict';

  const state = {
    rows: [],            // merged model, one row per catalog document
    classes: [],         // review class catalog from the overview file
    entities: {},        // gid -> {label, category}
    query: '',
    sort: 'id',
    filter: 'all',
  };

  const el = (tag, className, text) => {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  };

  const fold = (value) => (value || '')
    .normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/ä/g, 'ae').replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue').replace(/ß/g, 'ss');

  const statusLabel = {
    unverifiziert: 'unverified',
    in_arbeit: 'in progress',
    verifiziert: 'verified',
  };

  // ------------------------------------------------------------ data loading

  const load = async () => {
    const [overview, entities, catalog] = await Promise.all([
      fetch('data/entity_overview.json').then((r) => r.json()),
      fetch('data/entities.json').then((r) => r.json()),
      fetch('data/catalog.json').then((r) => r.json()),
    ]);
    state.classes = overview.classes;
    state.entities = entities;
    state.rows = catalog.documents.map((doc) => {
      const record = overview.documents[doc.id] ||
        { auto: 0, review: 0, classes: {}, entities: [] };
      const streams = doc.streams || {};
      return {
        id: doc.id,
        title: doc.title || '',
        author: doc.author || '',
        date: doc.date || '',
        status: (streams.entities || {}).status || 'unverifiziert',
        auto: record.auto,
        review: record.review,
        total: record.auto + record.review,
        classes: record.classes || {},
        entities: record.entities || [],
        checked: record.checked || null,
        search: fold(`${doc.id} ${doc.title} ${doc.author}`),
      };
    });
    renderSummary(overview.totals);
    renderLegendDescriptions();
    render();
  };

  // ------------------------------------------------------------ summary strip

  const renderSummary = (totals) => {
    const checked = totals.checked || {};
    const set = (id, value) => { document.getElementById(id).textContent = value; };
    set('eo-sum-docs', String(totals.documents));
    set('eo-sum-auto', totals.auto.toLocaleString('en-GB'));
    set('eo-sum-review', totals.review.toLocaleString('en-GB'));
    const total = checked.total || 0;
    const correct = checked.correct || 0;
    set('eo-sum-checked', total ? `${correct} / ${total}` : '0');
  };

  const renderLegendDescriptions = () => {
    const dl = document.getElementById('eo-class-legend');
    state.classes.forEach((cls) => {
      const item = el('div', 'eo-legend__chip');
      item.appendChild(el('strong', '', cls.label));
      item.appendChild(el('span', '', ` ${cls.description}`));
      dl.appendChild(item);
    });
  };

  // ------------------------------------------------------------ list rendering

  const visibleRows = () => {
    let rows = state.rows;
    if (state.query) rows = rows.filter((r) => r.search.includes(state.query));
    if (state.filter === 'review') rows = rows.filter((r) => r.review > 0);
    if (state.filter === 'checked') rows = rows.filter((r) => r.checked);
    if (state.filter === 'none') rows = rows.filter((r) => r.total === 0);
    const share = (r) => (r.total ? r.review / r.total : -1);
    const sorters = {
      id: (a, b) => Number(a.id) - Number(b.id),
      mentions: (a, b) => b.total - a.total || Number(a.id) - Number(b.id),
      reviewshare: (a, b) => share(b) - share(a) || b.review - a.review,
      auto: (a, b) => b.auto - a.auto || Number(a.id) - Number(b.id),
    };
    return [...rows].sort(sorters[state.sort] || sorters.id);
  };

  const render = () => {
    const list = document.getElementById('eo-list');
    list.textContent = '';
    const rows = visibleRows();
    document.getElementById('eo-result-count').textContent =
      `${rows.length} of ${state.rows.length} documents`;
    if (!rows.length) {
      list.appendChild(el('p', 'eo-empty', 'No documents match the current filter.'));
      return;
    }
    const fragment = document.createDocumentFragment();
    rows.forEach((row) => fragment.appendChild(renderDoc(row)));
    list.appendChild(fragment);
  };

  const renderDoc = (row) => {
    const details = el('details', 'eo-doc');
    details.dataset.doc = row.id;

    const summary = el('summary', 'eo-doc__summary');
    summary.appendChild(el('span', 'eo-doc__id', row.id));

    const title = el('span', 'eo-doc__title', row.title);
    const meta = [row.author, row.date].filter(Boolean).join(', ');
    if (meta) title.appendChild(el('span', 'eo-doc__meta', ` ${meta}`));
    summary.appendChild(title);

    const counts = el('span', 'eo-doc__counts');
    counts.appendChild(el('strong', '', String(row.auto)));
    counts.appendChild(document.createTextNode(' auto · '));
    counts.appendChild(el('em', '', String(row.review)));
    counts.appendChild(document.createTextNode(' review'));
    summary.appendChild(counts);

    summary.appendChild(renderBar(row));

    const status = el('span', `eo-status eo-status--${row.status}`);
    status.title = `Entities stream: ${statusLabel[row.status] || row.status}`;
    const srStatus = el('span', 'sr-only',
      `Entities stream ${statusLabel[row.status] || row.status}`);
    summary.appendChild(status);
    summary.appendChild(srStatus);

    details.appendChild(summary);
    details.addEventListener('toggle', () => {
      if (details.open && !details.dataset.rendered) {
        details.appendChild(renderBody(row));
        details.dataset.rendered = '1';
      }
    });
    return details;
  };

  const renderBar = (row) => {
    const bar = el('span', 'eo-bar');
    bar.setAttribute('role', 'img');
    const pct = row.total ? Math.round((row.auto / row.total) * 100) : 0;
    bar.setAttribute('aria-label', row.total
      ? `${pct} percent of ${row.total} mentions auto-marked`
      : 'no mentions');
    if (row.total) {
      const auto = el('span', 'eo-bar__auto');
      auto.style.width = `${(row.auto / row.total) * 100}%`;
      const review = el('span', 'eo-bar__review');
      review.style.width = `${(row.review / row.total) * 100}%`;
      bar.appendChild(auto);
      bar.appendChild(review);
    }
    return bar;
  };

  const renderBody = (row) => {
    const body = el('div', 'eo-doc__body');

    if (row.checked) {
      const wrong = (row.checked.wrong_entity || 0) + (row.checked.wrong_span || 0)
        + (row.checked.not_in_source || 0);
      const badge = el('span', wrong ? 'badge badge--warn' : 'badge badge--ok',
        `Hand-checked at the facsimile: ${row.checked.correct || 0} of `
        + `${row.checked.total} sampled marks correct`
        + (wrong ? `, ${wrong} confirmed error(s)` : ''));
      const wrap = el('p', 'eo-checked');
      wrap.appendChild(badge);
      body.appendChild(wrap);
    }

    if (row.review > 0) {
      const chips = el('div', 'eo-chips');
      state.classes.forEach((cls) => {
        const count = row.classes[cls.key];
        if (!count) return;
        const chip = el('span', 'eo-chip', `${cls.label} × ${count}`);
        chip.title = cls.description;
        chips.appendChild(chip);
      });
      body.appendChild(chips);
    }

    if (row.entities.length) {
      body.appendChild(renderEntityTable(row));
    } else {
      body.appendChild(el('p', 'eo-empty', 'No entity mentions found in this document.'));
    }

    const actions = el('p', 'eo-doc__actions');
    const link = el('a', 'btn btn--ghost', 'Open in the viewer (annotated reading view)');
    link.href = `viewer.html?doc=${encodeURIComponent(row.id)}`;
    actions.appendChild(link);
    body.appendChild(actions);
    return body;
  };

  const renderEntityTable = (row) => {
    const table = el('table', 'eo-table');
    const caption = el('caption', 'sr-only',
      `Entities annotated in document ${row.id}`);
    table.appendChild(caption);
    const head = el('thead');
    const headRow = el('tr');
    ['Entity', 'Category', 'Auto', 'Review', 'Review classes'].forEach((label, i) => {
      const th = el('th', i === 2 || i === 3 ? 'eo-num' : '', label);
      th.scope = 'col';
      headRow.appendChild(th);
    });
    head.appendChild(headRow);
    table.appendChild(head);

    const tbody = el('tbody');
    row.entities.forEach((entity) => {
      const info = state.entities[entity.gid] || {};
      const tr = el('tr');
      const name = el('td');
      name.appendChild(el('span', `eo-dot eo-dot--${info.category || 'unknown'}`));
      name.appendChild(document.createTextNode(info.label || entity.gid));
      tr.appendChild(name);
      tr.appendChild(el('td', '', info.category || '?'));
      tr.appendChild(el('td', 'eo-num', String(entity.auto)));
      tr.appendChild(el('td', 'eo-num', String(entity.review)));
      const classes = state.classes
        .filter((cls) => entity.classes[cls.key])
        .map((cls) => `${cls.label} × ${entity.classes[cls.key]}`)
        .join(', ');
      tr.appendChild(el('td', '', classes));
      tbody.appendChild(tr);
    });
    table.appendChild(tbody);
    return table;
  };

  // ------------------------------------------------------------ wiring

  const init = () => {
    document.getElementById('eo-search').addEventListener('input', (event) => {
      state.query = fold(event.target.value.trim());
      render();
    });
    document.getElementById('eo-sort').addEventListener('change', (event) => {
      state.sort = event.target.value;
      render();
    });
    document.getElementById('eo-filter').addEventListener('change', (event) => {
      state.filter = event.target.value;
      render();
    });
    load().catch((error) => {
      document.getElementById('eo-list').textContent =
        `Data could not be loaded (${error.message}). `
        + 'The page needs the generated files under data/.';
    });
  };

  document.addEventListener('DOMContentLoaded', init);
  return { init };
})();
